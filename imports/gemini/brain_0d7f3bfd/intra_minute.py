# Examine the intra-minute pattern of C
# 19:20:00 -> 106
# 19:20:15 -> 79
# 19:20:30 -> 67
# 19:20:45 -> 66

# 19:21:00 -> 115
# 19:21:15 -> 106
# 19:21:30 -> 79
# 19:21:45 -> 66

# 19:22:00 -> 106

data = [
    ('19:20:00', 106),
    ('19:20:15', 79),
    ('19:20:30', 67),
    ('19:20:45', 66),
    ('19:21:00', 115),
    ('19:21:15', 106),
    ('19:21:30', 79),
    ('19:21:45', 66),
    ('19:22:00', 106),
]

for t, c in data:
    sec = int(t.split(':')[2])
    print(f"{t}: sec={sec:02d}, C={c}")
